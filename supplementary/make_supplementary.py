#!/usr/bin/env python3
"""Generate the supplementary tables that run offline from the deposited files.

The manuscript cites Supplementary Tables S1-S12, Notes S1-S5, Figures S1-S4 and
Data S2, S11 and S12. This script emits the ones that are derivable from files in
this repository, each as a TSV with a header line naming its source, so that every
number in a generated table traces to a deposited file.

Items it cannot produce, and the input each needs, are listed in README.md here.

Usage:  python3 supplementary/make_supplementary.py [--out DIR]
"""
import argparse, collections, csv, io, os, sys

ROOT = os.environ.get("ESMATLAS_ROOT") or os.path.dirname(
    os.path.dirname(os.path.abspath(__file__)))


def read(rel):
    with io.open(os.path.join(ROOT, rel), encoding="utf-8") as fh:
        return list(csv.DictReader(fh, delimiter="\t"))


def write(out, name, source, header, rows):
    path = os.path.join(out, name)
    with io.open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write("# %s\n# generated by supplementary/make_supplementary.py from %s\n"
                 % (name, source))
        w = csv.writer(fh, delimiter="\t")
        w.writerow(header)
        w.writerows(rows)
    print("  %-44s %5d rows" % (name, len(rows)))
    return path


def norm(t):
    return t.replace(".pdb.gz", "").replace(".pdb", "")


def num(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def table_s1(out):
    """Same-fold and structure-only counts per query model."""
    src = "screen_v1/results/summary_per_query.tsv"
    rows = [[r["query"], r["atlas_hits_returned"], r["same_fold"], r["same_fold_div"],
             r["seq_detectable"], r["structure_only"], r["min_seq_id"], r["max_tm"]]
            for r in read(src)]
    return write(out, "Table_S1_hits_per_query.tsv", src,
                 ["query_model", "atlas_hits_returned", "same_fold",
                  "same_fold_below_30pct_id", "sequence_detectable",
                  "structure_only", "min_seq_id_pct", "max_tm_score"], rows)


def table_s2(out):
    """Habitat of each shortlisted protein, with the source of the assignment."""
    src = "screen_v2/results/bodysite_candidates.tsv"
    rows = [[r["mgyp"], r["query"], r["habitat_classes"], r["top_biome_lineage"],
             r["human_associated"], r["human_body_sites"], r["total_observations"],
             r["cluster_size"], r["biome_source"], r["in_current_release"],
             r["studies"], r["assemblies"]] for r in read(src)]
    return write(out, "Table_S2_habitat.tsv", src,
                 ["target", "query_model", "habitat_class", "biome_lineage",
                  "human_associated", "human_body_site", "observations",
                  "cluster_size", "metadata_source", "in_current_release",
                  "study", "assembly"], rows)


def table_s3(out):
    """Pfam recovery, one row per candidate-query pair."""
    src = "screen_v2/pfam/pfam_recovery.tsv"
    rows = [[r["candidate"], r["query_model"], r["query_acc"], r["query_pfam"],
             r["candidate_pfam"], r["shared_pfam"], r["candidate_has_pfam"],
             r["pfam_recovers_link"]] for r in read(src)]
    return write(out, "Table_S3_pfam_recovery.tsv", src,
                 ["target", "query_model", "query_accession", "query_pfam_families",
                  "candidate_pfam_families", "shared_families", "has_any_pfam_domain",
                  "shares_family_with_query"], rows)


def table_s6(out):
    """Docking affinity and pose placement per receptor."""
    src = "screen_v2/results/docking/dock_summary_sn38g.tsv"
    rows = [[r["receptor"], r["kind"], r["family"], r["n_seeds"], r["best_mean"],
             r["best_sd"], r["best_min"], r["best_max"], r["per_heavy"],
             r["min_dist_sugar"], r["min_dist_any_atom"], r["site_class"],
             r["tm_qnorm"], r["habitat"]] for r in read(src)]
    return write(out, "Table_S6_docking_sn38g.tsv", src,
                 ["receptor", "receptor_class", "family", "n_seeds",
                  "affinity_mean_kcal_mol", "affinity_sd", "affinity_min",
                  "affinity_max", "affinity_per_heavy_atom", "min_dist_sugar_A",
                  "min_dist_any_atom_A", "site_class", "tm_score_qnorm", "habitat"], rows)


def table_s7(out):
    """The same receptors against the bare drug and the bare sugar."""
    src = "screen_v2/results/docking/dock_by_receptor_ligand.tsv"
    rows = [[r["receptor"], r["kind"], r["family"], r["ligand"], r["n_seeds"],
             r["best_mean"], r["best_sd"], r["per_heavy"]] for r in read(src)]
    return write(out, "Table_S7_docking_by_ligand.tsv", src,
                 ["receptor", "receptor_class", "family", "ligand", "n_seeds",
                  "affinity_mean_kcal_mol", "affinity_sd",
                  "affinity_per_heavy_atom"], rows)


def table_s12(out):
    """Active-site classification of every structure-only candidate."""
    site = {(r["query"], norm(r["target"])): r
            for r in read("screen_v2/results/active_site_all_hits.tsv")}
    cand = read("screen_v1/results/candidates.tsv")
    src = "screen_v1/results/candidates.tsv and screen_v2/results/active_site_all_hits.tsv"
    rows = []
    for c in cand:
        k = (c["query"], norm(c["target"]))
        s = site.get(k)
        if s is None:
            continue
        n_cat, n_cat_id = num(s["n_catalytic"]), num(s["n_catalytic_identical"])
        if not n_cat or n_cat < 1:
            catalytic = "no_catalytic_residue_annotated"
        elif n_cat_id is not None and n_cat_id >= n_cat:
            catalytic = "all_kept"
        elif n_cat_id:
            catalytic = "partial"
        else:
            catalytic = "lost"
        frac = num(s["frac_identical"])
        if num(s["n_aligned"]) == 0:
            site_class = "not_checkable"
        elif frac is None:
            site_class = "not_checkable"
        elif frac >= 1.0 and (num(s["site_rmsd"]) or 99) <= 2.0 \
                and (num(s["site_dist_mad"]) or 99) <= 1.5:
            site_class = "site_complete"
        elif frac >= 0.7:
            site_class = "site_partial"
        else:
            site_class = "site_lost"
        rows.append([norm(c["target"]), c["query"], c["seq_id_pct"],
                     c["tm_score_qnorm"], c["phmmer_evalue"] or "no_hit",
                     s["n_sites"], s["n_aligned"], s["n_identical"],
                     s["frac_identical"], s["site_rmsd"], s["site_max_dev"],
                     s["site_dist_mad"], site_class, s["n_catalytic"],
                     s["n_catalytic_identical"], catalytic])
    counts = collections.Counter(r[12] for r in rows)
    cat_counts = collections.Counter(r[15] for r in rows)
    print("    site classes: %s" % dict(counts))
    print("    catalytic:    %s" % dict(cat_counts))
    return write(out, "Table_S12_site_classification.tsv", src,
                 ["target", "query_model", "seq_id_pct", "tm_score_qnorm",
                  "phmmer_evalue", "n_site_residues", "n_aligned", "n_identical",
                  "frac_identical", "site_rmsd_A", "site_max_dev_A",
                  "site_geometry_mad_A", "site_class", "n_catalytic",
                  "n_catalytic_identical", "catalytic_class"], rows)


def data_s2(out):
    """Provenance of every curated query active-site residue."""
    src = "screen_v2/results/query_sites_provenance.tsv"
    recs = read(src)
    cols = list(recs[0].keys()) if recs else []
    return write(out, "Data_S2_query_site_provenance.tsv", src, cols,
                 [[r[c] for c in cols] for r in recs])


def data_s11(out):
    """The docking box used for every receptor."""
    src = "screen_v2/results/docking/boxes_final.tsv"
    recs = read(src)
    cols = [c for c in (recs[0].keys() if recs else []) if c != "receptor_pdbqt"]
    return write(out, "Data_S11_docking_boxes.tsv", src, cols,
                 [[r[c] for c in cols] for r in recs])


def data_s12(out):
    """Ligand geometry, for the claim that SN-38 glucuronide fits the box."""
    src = "screen_v2/results/docking/ligands.tsv"
    recs = read(src)
    cols = [c for c in (recs[0].keys() if recs else []) if c not in ("sdf", "pdbqt")]
    return write(out, "Data_S12_ligand_geometry.tsv", src, cols,
                 [[r[c] for c in cols] for r in recs])


def note_s3_plddt(out):
    """Model confidence of the sampled candidates (Supplementary Note S4)."""
    src = "screen_v1/results/candidate_plddt.tsv"
    recs = read(src)
    vals = sorted(v for v in (num(r["plddt_mean"]) for r in recs) if v is not None)
    if vals:
        mid = vals[len(vals) // 2] if len(vals) % 2 else \
            (vals[len(vals) // 2 - 1] + vals[len(vals) // 2]) / 2
        print("    pLDDT: n=%d, median %.1f, min %.1f, all above 70: %s"
              % (len(vals), mid, vals[0], vals[0] > 70))
    return write(out, "Note_S4_candidate_plddt.tsv", src,
                 ["target", "plddt_mean", "n_residues"],
                 [[r["target"], r["plddt_mean"], r["n_res"]] for r in recs])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "supplementary", "tables"))
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    print("Writing supplementary tables to %s" % args.out)
    for fn in (table_s1, table_s2, table_s3, table_s6, table_s7, table_s12,
               data_s2, data_s11, data_s12, note_s3_plddt):
        fn(args.out)
    print("\nNot generated here (see supplementary/README.md): Tables S4, S5, S8, S9, "
          "S10, S11; Figure 7; the control half of Figures S2 and S3.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
